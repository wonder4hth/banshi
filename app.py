@app.route("/agents/<int:agent_id>/tasks/start", methods=["POST"])
@login_required
def task_start(agent_id):
    user = current_user()
    agent = get_owned_agent(agent_id, user["id"])
    if agent is None:
        return jsonify({"error": "not_found"}), 404

    data = request.get_json(silent=True) or {}
    task_name = (data.get("task_name") or "").strip() or "专注委托"
    task_desc = (data.get("task_desc") or "").strip()
    try:
        duration_min = int(data.get("duration_min", 25))
    except (TypeError, ValueError):
        duration_min = 25
    duration_min = max(1, min(180, duration_min))

    conn = get_db()
    conn.execute(
        """INSERT INTO tasks
           (user_id, agent_id, task_name, task_desc, duration_min, status, started_at, created_at)
           VALUES (?, ?, ?, ?, ?, 'in_progress', ?, ?)""",
        (user["id"], agent_id, task_name, task_desc, duration_min, db.now_iso(), db.now_iso()),
    )
    conn.commit()
    task_id = conn.execute("SELECT last_insert_rowid() AS id").fetchone()["id"]
    return jsonify({"task_id": task_id, "focus_url": url_for("focus", agent_id=agent_id, task_id=task_id)})


