@app.route("/records")
@login_required
def records():
    user = current_user()
    conn = get_db()

    tasks = conn.execute(
        "SELECT * FROM tasks WHERE user_id = ? AND status != 'in_progress' ORDER BY id DESC",
        (user["id"],),
    ).fetchall()

    today = date.today()
    month_prefix = f"{today.year:04d}-{today.month:02d}"
    month_tasks = [t for t in tasks if (t["ended_at"] or "").startswith(month_prefix)
                   or (t["created_at"] or "").startswith(month_prefix)]

    total_minutes = sum(t["duration_min"] for t in month_tasks)
    completed = sum(1 for t in month_tasks if t["outcome"] == "complete")
    total_count = len(month_tasks)
    completion_rate = round(100 * completed / total_count) if total_count else 0

    # simple calendar check-in: distinct days this month with any task activity
    checkin_days = sorted({
        (t["ended_at"] or t["created_at"] or "")[:10] for t in month_tasks
        if (t["ended_at"] or t["created_at"])
    })

    stories = conn.execute(
        """SELECT s.*, a.name AS agent_name FROM story_logs s
           JOIN agents a ON a.id = s.agent_id
           WHERE s.user_id = ? ORDER BY s.id DESC""",
        (user["id"],),
    ).fetchall()

    return render_template(
        "records.html",
        total_minutes=total_minutes,
        completion_rate=completion_rate,
        total_count=total_count,
        checkin_days=checkin_days,
        today=today,
        stories=stories,
    )


