@app.route("/agents/<int:agent_id>/chat")
@login_required
def chat(agent_id):
    user = current_user()
    agent = get_owned_agent(agent_id, user["id"])
    if agent is None:
        return redirect(url_for("agents_list"))

    conn = get_db()
    messages = conn.execute(
        "SELECT * FROM messages WHERE agent_id = ? AND user_id = ? ORDER BY id ASC",
        (agent_id, user["id"]),
    ).fetchall()

    if not messages:
        intro = llm_engine.generate_intro(agent)
        conn.execute(
            "INSERT INTO messages (user_id, agent_id, sender, content, created_at) VALUES (?,?,?,?,?)",
            (user["id"], agent_id, "agent", intro, db.now_iso()),
        )
        conn.commit()
        messages = conn.execute(
            "SELECT * FROM messages WHERE agent_id = ? AND user_id = ? ORDER BY id ASC",
            (agent_id, user["id"]),
        ).fetchall()

    # an in-progress task (if any) locks the chat input, per spec (专注期间暂停角色聊天)
    active_task = conn.execute(
        """SELECT * FROM tasks WHERE agent_id = ? AND user_id = ? AND status = 'in_progress'
           ORDER BY id DESC LIMIT 1""",
        (agent_id, user["id"]),
    ).fetchone()

    avatar_map = {a["id"]: a for a in dialogue.AVATARS}
    llm_ready = llm_engine.is_available()
    return render_template(
        "chat.html", agent=agent, messages=messages, active_task=active_task,
        avatar_map=avatar_map, llm_ready=llm_ready,
    )


