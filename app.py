import db
import dialogue
import llm_engine

BASE_DIR = Path(__file__).parent
SECRET_FILE = BASE_DIR / ".secret_key"


def load_or_create_secret() -> str:
    if SECRET_FILE.exists():
        return SECRET_FILE.read_text().strip()
    key = secrets.token_hex(32)
    SECRET_FILE.write_text(key)
    return key


app = Flask(__name__)
app.secret_key = load_or_create_secret()


# ---------------------------------------------------------------- helpers
def get_db():
    if "db" not in g:
        g.db = db.get_db()
    return g.db


@app.teardown_appcontext
def close_db(_exc):
    conn = g.pop("db", None)
    if conn is not None:
        conn.close()


def current_user():
    uid = session.get("user_id")
    if not uid:
        return None
    row = get_db().execute("SELECT * FROM users WHERE id = ?", (uid,)).fetchone()
    return row


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if current_user() is None:
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped


def get_owned_agent(agent_id: int, user_id: int):
    """Fetch an agent row, scoped to the owning user (memory isolation)."""
    return get_db().execute(
        "SELECT * FROM agents WHERE id = ? AND user_id = ?", (agent_id, user_id)
    ).fetchone()


def get_recent_history(conn, agent_id: int, user_id: int, limit: int = 8):
    """Oldest-first list of recent messages, for feeding conversational context to the LLM."""
    rows = conn.execute(
        "SELECT sender, content FROM messages WHERE agent_id = ? AND user_id = ? "
        "ORDER BY id DESC LIMIT ?",
        (agent_id, user_id, limit),
    ).fetchall()
    return list(reversed(rows))


ENGINE_LABELS = {"llm": "本地大模型", "template": "简单模板"}


@app.context_processor
def inject_globals():
    return {"current_user": current_user(), "styles": dialogue.STYLES,
             "attitudes": dialogue.ATTITUDES, "avatars": dialogue.AVATARS,
             "engines": ENGINE_LABELS}


