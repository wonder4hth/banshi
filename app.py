@app.route("/agents/<int:agent_id>/delete", methods=["POST"])
@login_required
def agent_delete(agent_id):
    user = current_user()
    conn = get_db()
    # Soft delete: a hard DELETE would cascade into tasks and story_logs, and the
    # records center should keep those. Chat history and unfinished tasks go.
    cur = conn.execute(
        "UPDATE agents SET deleted_at = ? WHERE id = ? AND user_id = ? AND deleted_at IS NULL",
        (db.now_iso(), agent_id, user["id"]),
    )
    if cur.rowcount:
        conn.execute("DELETE FROM messages WHERE agent_id = ? AND user_id = ?", (agent_id, user["id"]))
        conn.execute(
            "DELETE FROM tasks WHERE agent_id = ? AND user_id = ? AND status = 'in_progress'",
            (agent_id, user["id"]),
        )
    conn.commit()
    return redirect(url_for("agents_list"))


