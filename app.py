@app.route("/tasks/<int:task_id>/deliver", methods=["POST"])
@login_required
def task_deliver(task_id):
    user = current_user()
    conn = get_db()
    task = conn.execute(
        "SELECT * FROM tasks WHERE id = ? AND user_id = ?", (task_id, user["id"])
    ).fetchone()
    if task is None:
        return jsonify({"error": "not_found"}), 404

    outcome = (request.get_json(silent=True) or {}).get("outcome", "")
    if outcome not in ("complete", "distracted", "gave_up"):
        return jsonify({"error": "bad_outcome"}), 400

    agent = get_owned_agent(task["agent_id"], user["id"])

    conn.execute(
        "UPDATE tasks SET status = ?, outcome = ?, ended_at = ? WHERE id = ?",
        (outcome, outcome, db.now_iso(), task_id),
    )

    if agent["engine"] == "llm":
        line = llm_engine.generate_outcome_line(agent, task["task_name"], task["duration_min"], outcome)
    else:
        line = dialogue.generate_outcome_line(agent["speaking_style"], agent["distraction_attitude"], outcome)
    conn.execute(
        "INSERT INTO messages (user_id, agent_id, sender, content, created_at) VALUES (?,?,?,?,?)",
        (user["id"], agent["id"], "agent", line, db.now_iso()),
    )

    story = dialogue.build_story_entry(agent["name"], task["task_name"], task["duration_min"], outcome)
    conn.execute(
        """INSERT INTO story_logs (user_id, agent_id, task_id, entry_date, content, created_at)
           VALUES (?, ?, ?, ?, ?, ?)""",
        (user["id"], agent["id"], task_id, date.today().isoformat(), story, db.now_iso()),
    )
    conn.commit()

    return jsonify({
        "line": line,
        "chat_url": url_for("chat", agent_id=agent["id"]),
    })


