@app.route("/agents/<int:agent_id>/chat")
@login_required
def chat(agent_id):
    user = current_user()
    agent = get_owned_agent(agent_id, user["id"])
    if agent is None:
        return redirect(url_for("agents_list"))

    conn = get_db()
    messages = conn.execute(
        "SELECT * FROM messages WHERE agent_id = ? AND user_id = ? ORDER BY id ASC",
        (agent_id, user["id"]),
    ).fetchall()

    if not messages:
        if agent["engine"] == "llm":
            intro = llm_engine.generate_intro(agent)
        else:
            intro = dialogue.generate_intro(agent["speaking_style"])
        conn.execute(
            "INSERT INTO messages (user_id, agent_id, sender, content, created_at) VALUES (?,?,?,?,?)",
            (user["id"], agent_id, "agent", intro, db.now_iso()),
        )
        conn.commit()
        messages = conn.execute(
            "SELECT * FROM messages WHERE agent_id = ? AND user_id = ? ORDER BY id ASC",
            (agent_id, user["id"]),
        ).fetchall()

    # an in-progress task (if any) locks the chat input, per spec (专注期间暂停角色聊天)
    active_task = conn.execute(
        """SELECT * FROM tasks WHERE agent_id = ? AND user_id = ? AND status = 'in_progress'
           ORDER BY id DESC LIMIT 1""",
        (agent_id, user["id"]),
    ).fetchone()

    avatar_map = {a["id"]: a for a in dialogue.AVATARS}
    llm_ready = llm_engine.is_available() if agent["engine"] == "llm" else True
    return render_template(
        "chat.html", agent=agent, messages=messages, active_task=active_task,
        avatar_map=avatar_map, llm_ready=llm_ready,
    )


@app.route("/agents/<int:agent_id>/chat/send", methods=["POST"])
@login_required
def chat_send(agent_id):
    user = current_user()
    agent = get_owned_agent(agent_id, user["id"])
    if agent is None:
        return jsonify({"error": "not_found"}), 404

    text = (request.get_json(silent=True) or {}).get("text", "").strip()
    if not text:
        return jsonify({"error": "empty"}), 400

    conn = get_db()
    conn.execute(
        "INSERT INTO messages (user_id, agent_id, sender, content, created_at) VALUES (?,?,?,?,?)",
        (user["id"], agent_id, "user", text, db.now_iso()),
    )

    if agent["engine"] == "llm":
        history = get_recent_history(conn, agent_id, user["id"])
        reply_text, task_offer = llm_engine.generate_reply(agent, history, text)
    else:
        reply_text, task_offer = dialogue.generate_reply(agent["speaking_style"], text)
    conn.execute(
        "INSERT INTO messages (user_id, agent_id, sender, content, created_at) VALUES (?,?,?,?,?)",
        (user["id"], agent_id, "agent", reply_text, db.now_iso()),
    )
    conn.commit()

    resp = {"reply": reply_text, "task_offer": None}
    if task_offer:
        name, desc = task_offer
        resp["task_offer"] = {"name": name, "desc": desc}
    return jsonify(resp)


