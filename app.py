@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "GET":
        if current_user():
            return redirect(url_for("agents_list"))
        return render_template("login.html")

    identifier = request.form.get("identifier", "").strip()
    password = request.form.get("password", "")
    conn = get_db()
    row = conn.execute(
        "SELECT * FROM users WHERE email = ? OR username = ?",
        (identifier, identifier),
    ).fetchone()
    if row is None or not check_password_hash(row["password_hash"], password):
        return render_template("login.html", error="账号或密码不对哦，再试一次。",
                                identifier=identifier)
    session["user_id"] = row["id"]
    return redirect(url_for("agents_list"))


@app.route("/register", methods=["POST"])
def register():
    email = request.form.get("email", "").strip()
    username = request.form.get("username", "").strip()
    password = request.form.get("password", "")

    if not email or not username or not password:
        return render_template("login.html", reg_error="邮箱、用户名、密码都要填写哦。",
                                show_register=True)

    conn = get_db()
    existing = conn.execute("SELECT id FROM users WHERE email = ?", (email,)).fetchone()
    if existing:
        return render_template("login.html", reg_error="这个邮箱已经注册过啦，直接登录吧。",
                                show_register=True)

    conn.execute(
        "INSERT INTO users (email, username, password_hash, created_at) VALUES (?, ?, ?, ?)",
        (email, username, generate_password_hash(password), db.now_iso()),
    )
    conn.commit()
    row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
    session["user_id"] = row["id"]
    return redirect(url_for("agents_list"))


@app.route("/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


